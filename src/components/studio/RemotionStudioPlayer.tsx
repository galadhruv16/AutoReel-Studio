'use client';

import React, { useState, useRef, useEffect, useImperativeHandle, forwardRef, useCallback } from 'react';
import dynamic from 'next/dynamic';
import { Play, Film, Sparkles } from 'lucide-react';
import { StudioScene } from '../../types/studio';
import { DynamicStoryReel } from '../../remotion/compositions/DynamicStoryReel';

// Dynamic import with SSR disabled for Next.js browser canvas compatibility
const Player = dynamic(
  () => import('@remotion/player').then((mod) => mod.Player),
  {
    ssr: false,
    loading: () => (
      <div className="w-full h-full flex flex-col items-center justify-center bg-[#08090A] text-[#94A3B8] p-6 text-center">
        <div className="h-8 w-8 border-2 border-[#FF4F00] border-t-transparent rounded-full animate-spin mb-3" />
        <span className="text-xs font-mono text-[#EDEDED]">INITIALIZING REMOTION CANVAS</span>
        <span className="text-[10px] font-mono text-[#64748B] mt-1">1080×1920 • 60FPS</span>
      </div>
    ),
  }
);

interface ErrorBoundaryProps {
  children: React.ReactNode;
  fallback: React.ReactNode;
}

class PlayerErrorBoundary extends React.Component<ErrorBoundaryProps, { hasError: boolean }> {
  constructor(props: ErrorBoundaryProps) {
    super(props);
    this.state = { hasError: false };
  }

  static getDerivedStateFromError() {
    return { hasError: true };
  }

  componentDidCatch(error: any) {
    console.warn('Remotion canvas error caught by boundary:', error);
  }

  render() {
    if (this.state.hasError) {
      return this.props.fallback;
    }
    return this.props.children;
  }
}

export interface RemotionStudioPlayerHandle {
  play: () => void;
  pause: () => void;
  toggle: () => void;
  seek: (seconds: number) => void;
  setPlaybackRate: (rate: number) => void;
  toggleMute: () => boolean;
  setVolume: (volume: number) => void;
  getCurrentTime: () => number;
}

export interface RemotionStudioPlayerProps {
  topic: string;
  scenes: StudioScene[];
  captionStyle: 'kinetic' | 'minimal' | 'bold';
  accentColor?: string;
  audioUrl?: string | null;
  fallbackVideoSrc?: string;
  posterSrc?: string;
  onTimeUpdate?: (currentSeconds: number) => void;
  onSceneIndexChange?: (sceneIndex: number) => void;
  onPlayStateChange?: (isPlaying: boolean) => void;
}

export const RemotionStudioPlayer = forwardRef<RemotionStudioPlayerHandle, RemotionStudioPlayerProps>(
  (
    {
      topic,
      scenes,
      captionStyle,
      accentColor = '#FF4F00',
      audioUrl,
      fallbackVideoSrc,
      posterSrc,
      onTimeUpdate,
      onSceneIndexChange,
      onPlayStateChange,
    },
    ref
  ) => {
    const [isMounted, setIsMounted] = useState<boolean>(false);
    const [renderMode, setRenderMode] = useState<'remotion' | 'master'>('remotion');
    const [isPlayingFallback, setIsPlayingFallback] = useState<boolean>(false);
    const [isMutedState, setIsMutedState] = useState<boolean>(false);

    const videoRef = useRef<HTMLVideoElement | null>(null);
    const remotionPlayerRef = useRef<any>(null);

    useEffect(() => {
      setIsMounted(true);
    }, []);

    const fps = 30;
    const totalDurationSec = scenes.reduce((acc, s) => acc + s.duration, 0) || 30;
    const durationInFrames = Math.max(30, Math.ceil(totalDurationSec * fps));

    const safeScenes = scenes.length > 0 ? scenes : [
      {
        id: 'default_scene_1',
        index: 1,
        startTime: 0,
        endTime: 4,
        duration: 4,
        narration: topic || 'Dynamic visual explainers generated by AutoReel Studio.',
        visualDirection: 'Kinetic bold typography punch with rapid zoom-in',
        visualType: 'kinetic_text' as const,
        highlightWords: ['AutoReel', 'explainers'],
      },
    ];

    const syncCurrentSeconds = useCallback(
      (sec: number) => {
        if (onTimeUpdate) onTimeUpdate(sec);
        if (onSceneIndexChange) {
          const activeIdx = safeScenes.findIndex((s) => sec >= s.startTime && sec < s.endTime);
          if (activeIdx !== -1) {
            onSceneIndexChange(activeIdx);
          }
        }
      },
      [onTimeUpdate, onSceneIndexChange, safeScenes]
    );

    // Attach event listeners to Remotion player when mounted
    useEffect(() => {
      const player = remotionPlayerRef.current;
      if (!player) return;

      const handleTimeUpdate = (e: any) => {
        const frame = typeof e?.detail?.frame === 'number' ? e.detail.frame : player.getCurrentFrame?.() || 0;
        syncCurrentSeconds(frame / fps);
      };

      const handlePlay = () => {
        onPlayStateChange?.(true);
      };

      const handlePause = () => {
        onPlayStateChange?.(false);
      };

      player.addEventListener('timeupdate', handleTimeUpdate);
      player.addEventListener('play', handlePlay);
      player.addEventListener('pause', handlePause);

      return () => {
        player.removeEventListener('timeupdate', handleTimeUpdate);
        player.removeEventListener('play', handlePlay);
        player.removeEventListener('pause', handlePause);
      };
    }, [isMounted, renderMode, fps, syncCurrentSeconds, onPlayStateChange]);

    // Expose control methods to parent component (Stage03Review)
    useImperativeHandle(
      ref,
      () => ({
        play: () => {
          if (renderMode === 'remotion' && remotionPlayerRef.current) {
            remotionPlayerRef.current.play();
          } else if (videoRef.current) {
            videoRef.current.play().then(() => {
              setIsPlayingFallback(true);
              onPlayStateChange?.(true);
            }).catch(() => {});
          }
        },
        pause: () => {
          if (renderMode === 'remotion' && remotionPlayerRef.current) {
            remotionPlayerRef.current.pause();
          } else if (videoRef.current) {
            videoRef.current.pause();
            setIsPlayingFallback(false);
            onPlayStateChange?.(false);
          }
        },
        toggle: () => {
          if (renderMode === 'remotion' && remotionPlayerRef.current) {
            if (remotionPlayerRef.current.isPlaying?.()) {
              remotionPlayerRef.current.pause();
            } else {
              remotionPlayerRef.current.play();
            }
          } else if (videoRef.current) {
            if (videoRef.current.paused) {
              videoRef.current.play().then(() => {
                setIsPlayingFallback(true);
                onPlayStateChange?.(true);
              }).catch(() => {});
            } else {
              videoRef.current.pause();
              setIsPlayingFallback(false);
              onPlayStateChange?.(false);
            }
          }
        },
        seek: (seconds: number) => {
          const clamped = Math.max(0, Math.min(totalDurationSec, seconds));
          if (renderMode === 'remotion' && remotionPlayerRef.current) {
            const targetFrame = Math.round(clamped * fps);
            remotionPlayerRef.current.seekTo(targetFrame);
          } else if (videoRef.current) {
            videoRef.current.currentTime = clamped;
          }
          syncCurrentSeconds(clamped);
        },
        setPlaybackRate: (rate: number) => {
          if (videoRef.current) {
            videoRef.current.playbackRate = rate;
          }
          if (remotionPlayerRef.current?.setPlaybackRate) {
            remotionPlayerRef.current.setPlaybackRate(rate);
          }
        },
        toggleMute: () => {
          const nextMuted = !isMutedState;
          setIsMutedState(nextMuted);
          if (videoRef.current) {
            videoRef.current.muted = nextMuted;
          }
          if (remotionPlayerRef.current) {
            if (nextMuted) {
              remotionPlayerRef.current.mute?.();
            } else {
              remotionPlayerRef.current.unmute?.();
            }
          }
          return nextMuted;
        },
        setVolume: (volume: number) => {
          const clamped = Math.max(0, Math.min(1, volume));
          if (videoRef.current) {
            videoRef.current.volume = clamped;
          }
          if (remotionPlayerRef.current?.setVolume) {
            remotionPlayerRef.current.setVolume(clamped);
          }
        },
        getCurrentTime: () => {
          if (renderMode === 'remotion' && remotionPlayerRef.current) {
            const frame = remotionPlayerRef.current.getCurrentFrame?.() || 0;
            return frame / fps;
          }
          return videoRef.current?.currentTime || 0;
        },
      }),
      [renderMode, fps, totalDurationSec, isMutedState, syncCurrentSeconds, onPlayStateChange]
    );

    const handleFallbackPlayPause = () => {
      if (!videoRef.current) return;
      if (isPlayingFallback) {
        videoRef.current.pause();
        setIsPlayingFallback(false);
        onPlayStateChange?.(false);
      } else {
        videoRef.current.play().then(() => {
          setIsPlayingFallback(true);
          onPlayStateChange?.(true);
        }).catch(() => {});
      }
    };

    const handleFallbackTimeUpdate = () => {
      if (!videoRef.current) return;
      syncCurrentSeconds(videoRef.current.currentTime);
    };

    return (
      <div className="relative w-full max-w-[310px] aspect-[9/16] rounded-3xl overflow-hidden border-2 border-[#232634] bg-[#000000] shadow-2xl shadow-black/80 flex flex-col justify-between group">
        {/* Top Header Mode Switcher Bar */}
        <div className="absolute top-0 left-0 right-0 z-30 flex items-center justify-between p-3 bg-gradient-to-b from-black/80 via-black/40 to-transparent pointer-events-auto">
          {fallbackVideoSrc && fallbackVideoSrc.startsWith('/renders/') ? (
            <div className="flex items-center gap-1 bg-[#08090A]/90 p-0.5 rounded-full border border-[#232634]">
              <button
                type="button"
                onClick={() => setRenderMode('remotion')}
                className={`flex items-center gap-1 px-2.5 py-1 rounded-full text-[10px] font-mono transition ${
                  renderMode === 'remotion'
                    ? 'bg-[#FF4F00] text-white shadow-sm font-bold'
                    : 'text-[#94A3B8] hover:text-white'
                }`}
              >
                <Sparkles className="h-2.5 w-2.5" />
                <span>AI Canvas</span>
              </button>
              <button
                type="button"
                onClick={() => setRenderMode('master')}
                className={`flex items-center gap-1 px-2.5 py-1 rounded-full text-[10px] font-mono transition ${
                  renderMode === 'master'
                    ? 'bg-emerald-500 text-white font-bold'
                    : 'text-[#94A3B8] hover:text-white'
                }`}
              >
                <Film className="h-2.5 w-2.5" />
                <span>Rendered MP4</span>
              </button>
            </div>
          ) : (
            <div className="flex items-center gap-1.5 bg-[#08090A]/90 px-3 py-1 rounded-full border border-[#232634]">
              <Sparkles className="h-3 w-3 text-[#FF4F00]" />
              <span className="text-[10px] font-mono text-white font-bold tracking-wide">REMOTION AI CANVAS</span>
            </div>
          )}

          <span className="rounded-full bg-[#14161F]/80 backdrop-blur-md px-2 py-0.5 text-[10px] font-mono text-[#FF4F00] border border-[#FF4F00]/30">
            1080×1920 • 60FPS
          </span>
        </div>

        {/* Viewport Content */}
        <div className="w-full h-full relative">
          {renderMode === 'remotion' ? (
            /* Live Remotion React Vector Canvas with ErrorBoundary */
            <div className="w-full h-full bg-[#08090A] flex items-center justify-center">
              {isMounted ? (
                <PlayerErrorBoundary
                  fallback={
                    <div className="w-full h-full flex flex-col items-center justify-center bg-[#08090A] text-[#94A3B8] p-6 text-center">
                      <div className="h-8 w-8 rounded-full border-2 border-[#FF4F00] flex items-center justify-center text-xs font-bold text-[#FF4F00] mb-2">!</div>
                      <span className="text-xs font-mono text-[#EDEDED]">CANVAS REFRESH REQUIRED</span>
                      <span className="text-[10px] font-mono text-[#64748B] mt-1">Click transport play to re-mount</span>
                    </div>
                  }
                >
                  <Player
                    ref={remotionPlayerRef}
                    component={DynamicStoryReel as any}
                    inputProps={{
                      topic,
                      scenes: safeScenes,
                      captionStyle,
                      accentColor,
                      audioUrl: audioUrl || null,
                    }}
                    durationInFrames={durationInFrames}
                    fps={fps}
                    compositionWidth={1080}
                    compositionHeight={1920}
                    style={{
                      width: '100%',
                      height: '100%',
                    }}
                    controls
                    loop
                    autoPlay={false}
                  />
                </PlayerErrorBoundary>
              ) : (
                <div className="w-full h-full flex flex-col items-center justify-center bg-[#08090A] text-[#94A3B8] p-6 text-center">
                  <div className="h-8 w-8 border-2 border-[#FF4F00] border-t-transparent rounded-full animate-spin mb-3" />
                  <span className="text-xs font-mono text-[#EDEDED]">INITIALIZING CANVAS</span>
                </div>
              )}
            </div>
          ) : (
            /* Pre-rendered Master Video Player */
            <div className="w-full h-full relative flex flex-col items-center justify-center p-6 text-center bg-[#08090A]">
              {fallbackVideoSrc ? (
                <>
                  <video
                    ref={videoRef}
                    src={fallbackVideoSrc}
                    poster={posterSrc}
                    playsInline
                    loop
                    onTimeUpdate={handleFallbackTimeUpdate}
                    onClick={handleFallbackPlayPause}
                    className="w-full h-full object-cover cursor-pointer"
                  />
                  {!isPlayingFallback && (
                    <button
                      type="button"
                      onClick={handleFallbackPlayPause}
                      className="absolute inset-0 z-20 flex items-center justify-center bg-black/40 backdrop-blur-[2px] transition group-hover:bg-black/30"
                    >
                      <div className="flex h-16 w-16 items-center justify-center rounded-full bg-[#FF4F00] text-white shadow-xl shadow-[#FF4F00]/40 transition transform group-hover:scale-105 active:scale-95">
                        <Play className="h-7 w-7 translate-x-0.5" />
                      </div>
                    </button>
                  )}
                </>
              ) : (
                <div className="space-y-3">
                  <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-2xl bg-[#14161F] border border-[#232634] text-[#FF4F00]">
                    <Film className="h-6 w-6" />
                  </div>
                  <h4 className="text-sm font-semibold text-[#EDEDED]">Master MP4 Not Rendered</h4>
                  <p className="text-xs text-[#94A3B8] max-w-[220px]">
                    Preview your real-time animation on the <strong>AI Canvas</strong>, or proceed to Stage 4 to render the full 1080p 60FPS MP4.
                  </p>
                  <button
                    type="button"
                    onClick={() => setRenderMode('remotion')}
                    className="inline-flex items-center gap-1.5 rounded-xl bg-[#FF4F00] px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-[#FF3B00] transition"
                  >
                    <Sparkles className="h-3 w-3" />
                    <span>Switch to AI Canvas</span>
                  </button>
                </div>
              )}
            </div>
          )}
        </div>
      </div>
    );
  }
);

RemotionStudioPlayer.displayName = 'RemotionStudioPlayer';
